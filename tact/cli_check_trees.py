"""Command-line interface module to check TACT results."""

import csv
import functools
import math
import multiprocessing
import os
from typing import TextIO

import click
import dendropy

from . import _blas_threads  # noqa: F401  # before anything imports NumPy
from .console import progressbar
from .names import adopt_names, written_name
from .tree_util import get_birth_death_rates, get_monophyletic_node, get_tip_labels, update_tree_view
from .validation import read_newick, validate_newick_path


def read_tree(
    ctx: click.Context, name: str, path: str, namespace: dendropy.TaxonNamespace | None = None
) -> dendropy.Tree:
    """Read the tree given to parameter `name`.

    With a `namespace`, its tips are moved onto the taxa there, adding any missing, and its node ages are set.
    """
    param = next(p for p in ctx.command.params if p.name == name)
    with open(path, encoding="utf-8-sig") as fh:
        tree = read_newick(ctx, param, fh.read())
    if namespace is not None:
        adopt_names(tree, namespace, add_missing=True)
        update_tree_view(tree)
    return tree


def analyze_taxon(
    bb_tips: set[str], st_tips: set[str], backbone: dendropy.Tree, simtaxed: dendropy.Tree, taxon_node: dendropy.Node
) -> list[object] | None:
    """Perform various checks for a given taxon."""
    taxon = taxon_node.label
    if not taxon:
        return None
    species = {x.taxon.label for x in taxon_node.leaf_iter()}

    notes = []

    # does this clade even exist in the backbone?
    bb_species = species.intersection(bb_tips)
    if bb_species:
        bb_mrca = get_monophyletic_node(backbone, bb_species)
        if bb_mrca:
            bb_ntax = len(bb_mrca.leaf_nodes())
            bb_birth, bb_death = get_birth_death_rates(bb_mrca, min(bb_ntax / len(species), 1), include_root=True)
            if bb_ntax > len(species):
                notes.append("BACKBONE clade has more tips than the taxonomy suggests")
        else:
            bb_ntax = bb_birth = bb_death = None
    else:
        bb_ntax = 0
        bb_birth = bb_death = bb_mrca = None

    st_mrca = get_monophyletic_node(simtaxed, species.intersection(st_tips))
    if st_mrca:
        st_ntax = len(st_mrca.leaf_nodes())
        st_birth, st_death = get_birth_death_rates(st_mrca, min(st_ntax / len(species), 1), include_root=True)
        if st_ntax > len(species):
            notes.append("SIMULATED clade has more tips than the taxonomy suggests")
    else:
        st_ntax = st_birth = st_death = None

    if bool(bb_mrca) != bool(st_mrca) and bb_mrca is not None:
        notes.append("BACKBONE and SIMULATED trees differ in monophyly for this taxa")

    return [
        written_name(taxon),
        len(species),
        bb_ntax,
        st_ntax,
        bool(bb_mrca),
        bool(st_mrca),
        bb_birth,
        st_birth,
        bb_death,
        st_death,
        ", ".join(notes),
    ]


@click.command()
@click.version_option(package_name="tact")
@click.argument("simulated", type=click.Path(exists=True, dir_okay=False), callback=validate_newick_path)
@click.option(
    "--backbone",
    type=click.Path(exists=True, dir_okay=False),
    required=True,
    help="backbone phylogeny",
    callback=validate_newick_path,
)
@click.option(
    "--taxonomy",
    type=click.Path(exists=True, dir_okay=False),
    required=True,
    callback=validate_newick_path,
    help="taxonomic phylogeny. Possibly created by `tact_build_taxonomic_tree`",
)
@click.option(
    "--output",
    # not lazy, so that a missing directory is reported before the checks run
    type=click.File("w", lazy=False),
    help="Output CSV file report (defaults to standard output)",
    default="-",
)
@click.option(
    "--cores",
    help="number of parallel cores to use",
    default=os.cpu_count() or 1,
    type=click.IntRange(1, os.cpu_count() or 1, clamp=True),
)
@click.option("--chunksize", help="number of tree nodes to allocate to each core", type=click.IntRange(1))
def main(simulated: str, backbone: str, taxonomy: str, output: TextIO, cores: int, chunksize: int | None) -> None:
    """Check a SIMULATED phylogeny for consistency with its backbone source tree and a taxonomy.

    The SIMULATED phylogeny should have been generated by the tact_add_taxa script.
    All phylogenies should be in Newick format.
    """
    ctx = click.get_current_context()
    taxonomy_tree = read_tree(ctx, "taxonomy", taxonomy)
    tn = taxonomy_tree.taxon_namespace
    click.echo("Taxonomy OK", err=True)
    backbone_tree = read_tree(ctx, "backbone", backbone, tn)
    click.echo("Backbone OK", err=True)
    simulated_tree = read_tree(ctx, "simulated", simulated, tn)
    click.echo("Simulated OK", err=True)

    with multiprocessing.Pool(processes=cores) as pool:
        click.echo(f"Using {cores} parallel cores", err=True)

        bb_tips = get_tip_labels(backbone_tree)
        st_tips = get_tip_labels(simulated_tree)

        # Start calculating ASAP
        wrap = functools.partial(analyze_taxon, bb_tips, st_tips, backbone_tree, simulated_tree)
        nnodes = len(taxonomy_tree.internal_nodes(exclude_seed_node=True))
        if chunksize is None:
            chunksize = max(5, math.ceil(nnodes / cores / 10))
        # We use preorder because the root is going to take the longest to
        # run calculations. Allocating things to cores takes a non-negigible
        # amount of time so we want the root to be running for the longest.
        nodes = taxonomy_tree.preorder_internal_node_iter(exclude_seed_node=True)
        it = pool.imap_unordered(wrap, nodes, chunksize=chunksize)

        writer = csv.writer(output)
        writer.writerow(
            [
                "node",
                "taxonomy_tips",
                "backbone_tips",
                "simulated_tips",
                "backbone_monophyletic",
                "simulated_monophyletic",
                "backbone_birth",
                "simulated_birth",
                "backbone_death",
                "simulated_death",
                "warnings",
            ]
        )

        with progressbar(it, label="Checking", length=nnodes) as prog:
            for result in prog:
                if result:
                    writer.writerow(result)


if __name__ == "__main__":
    main()
